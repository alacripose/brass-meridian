// Measured 6.0 accounting. state/scope.json carries one have/need count per
// area. This tool writes state/progress.json, docs/SCOPE.md, and the percent
// that tools/status.mjs prints. No weights and no estimated fractions.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const scope = JSON.parse(readFileSync(resolve(root, "state/scope.json"), "utf8"));
const problems = [];

if (scope.label !== "6.0") problems.push(`label is ${scope.label ?? "missing"}`);
const areas = Array.isArray(scope.areas) ? scope.areas : [];
if (!areas.length) problems.push("scope has no areas");

let totalHave = 0;
let totalNeed = 0;
const seen = new Set();
const summary = [];

for (const area of areas) {
  if (!/^A\d{2}$/.test(area.id ?? "")) problems.push(`${area.id ?? "?"} has a bad id`);
  if (seen.has(area.id)) problems.push(`${area.id} is duplicated`);
  seen.add(area.id);
  if (!area.name) problems.push(`${area.id} has no name`);
  if (!Number.isInteger(area.have) || !Number.isInteger(area.need)) problems.push(`${area.id} counts are not integers`);
  if (area.have < 0 || area.need <= 0 || area.have > area.need) problems.push(`${area.id} counts are out of range`);
  if (!Array.isArray(area.evidence) || !area.evidence.length) problems.push(`${area.id} has no evidence path`);
  for (const path of area.evidence ?? []) {
    if (!existsSync(resolve(root, path))) problems.push(`${area.id} evidence missing: ${path}`);
  }
  if (!Array.isArray(area.missing) || !area.missing.length) problems.push(`${area.id} has no missing list`);
  if ((area.missing ?? []).length > Math.max(1, area.need - area.have)) {
    problems.push(`${area.id} lists more missing than the gap`);
  }
  if (!area.next) problems.push(`${area.id} has no next step`);
  totalHave += area.have;
  totalNeed += area.need;
  summary.push({
    id: area.id,
    name: area.name,
    have: area.have,
    need: area.need,
    percent: Math.round((area.have / area.need) * 1000) / 10,
    evidence: area.evidence,
    missing: area.missing,
    next: area.next,
  });
}

if (totalNeed === 0) problems.push("scope has no need count");
const percent = totalNeed ? Math.round((totalHave / totalNeed) * 1000) / 10 : 0;
if (percent >= 10) problems.push(`percentage ${percent} is not single digit`);

const progress = {
  updated: scope.updated,
  label: scope.label,
  note: scope.note,
  rubric: scope.rubric,
  areas: summary,
  totals: { have: totalHave, need: totalNeed, percent },
  todo: summary.filter((area) => area.have < area.need).map((area) => ({
    id: area.id,
    title: area.name,
    next: area.next,
  })),
  limits: [
    "No accounts, server, or multiplayer.",
    "The planet, cube-sphere and voxel LOD are not built.",
    "Region zoom is a 6.0 gate and is not built.",
    "The 64-bit seed is stored, but named sub-seeds are not.",
    "The percentage counts measured capabilities, not hours.",
  ],
};

const md = [];
md.push("<!-- generated by tools/scope.mjs from state/scope.json -->");
md.push("# 6.0 scope");
md.push("");
md.push(`Measured inventory: ${totalHave} of ${totalNeed} capabilities, or ${percent}%.`);
md.push("");
md.push(`Rubric: ${scope.rubric}`);
md.push("");
md.push("| Area | Have | Need | Done | Evidence |");
md.push("| --- | ---: | ---: | ---: | --- |");
for (const area of summary) md.push(`| ${area.id} ${area.name} | ${area.have} | ${area.need} | ${area.percent}% | ${area.evidence.join(", ")} |`);
md.push("");
md.push("## Open work");
md.push("");
for (const area of summary) {
  if (area.have >= area.need) continue;
  md.push(`### ${area.id} ${area.name}`);
  md.push("");
  md.push(`Missing: ${area.missing.join(", ")}.`);
  md.push(`Next: ${area.next}`);
  md.push("");
}

writeFileSync(resolve(root, "state/progress.json"), JSON.stringify(progress, null, 2) + "\n");
writeFileSync(resolve(root, "docs/SCOPE.md"), md.join("\n"));

if (problems.length) {
  console.error(`SCOPE-FAIL ${problems.join(" | ")}`);
  process.exit(1);
}
console.log(`SCOPE-PASS label=${scope.label} areas=${summary.length} have=${totalHave} need=${totalNeed} percent=${percent}%`);
