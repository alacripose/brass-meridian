// Generated status. The percentage comes from state/progress.json, which is
// the measured 6.0 have/need count. Evidence paths must exist.

import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const progress = JSON.parse(readFileSync(resolve(root, "state/progress.json"), "utf8"));
const totals = progress.totals;
const stamp = new Date().toISOString().slice(0, 16).replace("T", " ") + " UTC";

const receipts = [];
for (const name of ["wasm-build", "rust-test", "test", "build", "probe", "gate"]) {
  const path = resolve(root, `artifacts/receipts/${name}.json`);
  if (!existsSync(path)) {
    receipts.push({ name, ok: false, at: "missing" });
    continue;
  }
  const data = JSON.parse(readFileSync(path, "utf8"));
  receipts.push({ name, ok: Boolean(data.ok), at: data.at ?? "" });
}

const ledger = [];
for (const type of ["failures", "health", "probes", "tests", "improvements", "reconciliation"]) {
  const dir = resolve(root, "ledger", type);
  let rows = 0;
  if (existsSync(dir)) {
    for (const file of readdirSync(dir).filter((n) => n.endsWith(".jsonl"))) {
      rows += readFileSync(resolve(dir, file), "utf8").split(/\r?\n/).filter(Boolean).length;
    }
  }
  ledger.push({ type, rows });
}

const lines = [];
lines.push("<!-- generated by tools/status.mjs -->");
lines.push("# Status");
lines.push("");
lines.push(`6.0 inventory ${totals.percent}% — ${stamp}.`);
lines.push("");
lines.push("This counts measured 6.0 capabilities, not hours. The label is 6.0.");
lines.push("");
lines.push("| Area | Have | Need | Done | Evidence |");
lines.push("| --- | ---: | ---: | ---: | --- |");
for (const area of progress.areas) {
  lines.push(`| ${area.id} ${area.name} | ${area.have} | ${area.need} | ${area.percent}% | ${area.evidence.join(", ")} |`);
}
lines.push("");
lines.push("## Proof");
lines.push("");
lines.push("| Receipt | State | At |");
lines.push("| --- | --- | --- |");
for (const item of receipts) lines.push(`| ${item.name} | ${item.ok ? "pass" : "missing or fail"} | ${item.at || "—"} |`);
lines.push("");
lines.push("## Ledger");
lines.push("");
lines.push("| Type | Rows |");
lines.push("| --- | ---: |");
for (const item of ledger) lines.push(`| ${item.type} | ${item.rows} |`);
lines.push("");
lines.push("## Next");
lines.push("");
for (const item of progress.todo.slice(0, 10)) lines.push(`- ${item.id} — ${item.title} — ${item.next}`);
if (progress.todo.length > 10) lines.push(`- ${progress.todo.length - 10} more open areas are in docs/SCOPE.md.`);
lines.push("");
lines.push("## Limits");
lines.push("");
for (const limit of progress.limits ?? []) lines.push(`- ${limit}`);
lines.push("");
lines.push("Edit `state/scope.json`, then run `npm run scope`.");
lines.push("");
writeFileSync(resolve(root, "STATUS.md"), lines.join("\n"));
console.log(`6.0 INVENTORY ${totals.percent}%`);
