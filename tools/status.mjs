// Generated status. The percentage comes from state/progress.json, which is
// the one place a phase's completion is declared. Evidence paths must exist.

import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const progress = JSON.parse(readFileSync(resolve(root, "state/progress.json"), "utf8"));
const phases = progress.phases;
const points = phases.reduce((sum, phase) => sum + phase.weight * phase.done, 0);
const percent = Math.round(points * 10) / 10;
const stamp = new Date().toISOString().slice(0, 16).replace("T", " ") + " UTC";

const receipts = [];
for (const name of ["wasm-build", "rust-test", "test", "build", "probe", "gate"]) {
  const path = resolve(root, `artifacts/receipts/${name}.json`);
  if (!existsSync(path)) {
    receipts.push({ name, ok: false, at: "missing" });
    continue;
  }
  const data = JSON.parse(readFileSync(path, "utf8"));
  receipts.push({ name, ok: Boolean(data.ok), at: data.at ?? "" });
}

const ledger = [];
for (const type of ["failures", "health", "probes", "tests", "improvements"]) {
  const dir = resolve(root, "ledger", type);
  let rows = 0;
  if (existsSync(dir)) {
    for (const file of readdirSync(dir).filter((n) => n.endsWith(".jsonl"))) {
      rows += readFileSync(resolve(dir, file), "utf8").split(/\r?\n/).filter(Boolean).length;
    }
  }
  ledger.push({ type, rows });
}

const lines = [];
lines.push("<!-- generated by tools/status.mjs -->");
lines.push("# Status");
lines.push("");
lines.push(`Project ${percent}% — ${stamp}.`);
lines.push("");
lines.push("This counts what is proved in this repository. It is not a promise.");
lines.push("");
lines.push("| Phase | Weight | Done | Points | Evidence |");
lines.push("| --- | ---: | ---: | ---: | --- |");
for (const phase of phases) {
  lines.push(`| ${phase.id} ${phase.name} | ${phase.weight} | ${Math.round(phase.done * 100)}% | ${(phase.weight * phase.done).toFixed(1)} | ${phase.evidence ?? "—"} |`);
}
lines.push("");
lines.push("## Proof");
lines.push("");
lines.push("| Receipt | State | At |");
lines.push("| --- | --- | --- |");
for (const item of receipts) lines.push(`| ${item.name} | ${item.ok ? "pass" : "missing or fail"} | ${item.at || "—"} |`);
lines.push("");
lines.push("## Ledger");
lines.push("");
lines.push("| Type | Rows |");
lines.push("| --- | ---: |");
for (const item of ledger) lines.push(`| ${item.type} | ${item.rows} |`);
lines.push("");
lines.push("## Next");
lines.push("");
for (const item of progress.todo.filter((todo) => todo.state !== "done")) {
  lines.push(`- ${item.id} — ${item.title}`);
}
lines.push("");
lines.push("## Limits");
lines.push("");
for (const limit of progress.limits ?? []) lines.push(`- ${limit}`);
lines.push("");
lines.push("Edit `state/progress.json`, then run `npm run status`.");
lines.push("");
writeFileSync(resolve(root, "STATUS.md"), lines.join("\n"));
console.log(`PROJECT ${percent}%`);
